export function tr(lang: Lang, key: StrKey, vars?: Record<string, string | number>): string {
  let s: string = STR[lang][key]
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
    }
  }
  return s
}

export function fmtCalendar(lang: Lang, iso: string): string {
  const d = new Date(iso)
  if (!iso || isNaN(d.getTime())) return iso
  return d.toLocaleDateString(lang === 'ru' ? 'ru-RU' : 'en-US', { day: 'numeric', month: 'long', year: 'numeric' })
}

export function fmtCalendarShort(lang: Lang, iso: string): string {
  const d = new Date(iso)
  if (!iso || isNaN(d.getTime())) return iso
  return d.toLocaleDateString(lang === 'ru' ? 'ru-RU' : 'en-US', { day: 'numeric', month: 'short', year: 'numeric' })
}

export function fmtBookDate(lang: Lang, year: number | null, day: number): string {
  if (lang === 'ru') return year != null ? `Год ${year}, день ${day}` : `День ${day}`
  return year != null ? `Year ${year}, day ${day}` : `Day ${day}`
}